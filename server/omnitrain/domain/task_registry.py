"""Task registry: the lookup facade over the task plugins in `omnitrain/tasks/`.

A task is one `Task` subclass (see `omnitrain.tasks.base`): what a dataset item for it looks like, its
ground-truth shape, the snapshot columns the builder emits and the request/response shape inference needs,
independent of any training framework. What used to be a hard-coded list in this module is now a plugin
registry, so adding a task is dropping in a class; this module keeps the names every consumer already imports
(`TaskDescriptor`, `get_task_descriptor`, `TASK_REGISTRY`, ...) and the helpers built on them.

It drives project creation, upload validation, snapshot column derivation, inference request/response shapes
and export READMEs on the backend, and (via schema/task_registry.json, generated by
scripts/export_schema.py) the task picker and per-modality UI on the frontend.

Whether a task is actually trainable right now is a runtime question, not a static one: see
`omnitrain.plugins.backends.registry.trainable_backends`. `status` only distinguishes tasks OmniTrain can represent at
all ("planned" ones have no annotation/columns story yet) from ones that are just waiting on a backend plugin.
"""

