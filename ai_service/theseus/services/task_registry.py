def _ludwig_task(
    id: ProjectTask,
    label: str,
    modality: DatasetModality,
    status: Literal["stable", "experimental"],
    item_spec: ItemSpec,
    annotation: AnnotationSpec,
    columns: list[ColumnSpec],
    *,
    inputs: list[dict[str, Any]],
    outputs: list[dict[str, Any]],
    encoders: list[EncoderChoice],
    model_type: Literal["ecd", "llm"] = "ecd",
    knobs: TrainerKnobSpec | None = None,
) -> TaskDescriptor:
    return TaskDescriptor(
        id=id,
        label=label,
        modality=modality,
        backend="ludwig",
        status=status,
        item_spec=item_spec,
        annotation=annotation,
        columns=columns,
        ludwig=LudwigTaskConfig(
            model_type=model_type,
            input_features=inputs,
            output_features=outputs,
            encoders=encoders,
            trainer_knobs=knobs or (_llm_knobs() if model_type == "llm" else _default_knobs()),
        ),
    )


def _planned(
    id: ProjectTask, label: str, modality: DatasetModality, ann: AnnotationType, needs_classes: bool
) -> TaskDescriptor:
    """Genuinely blocked, not just unbuilt: Ludwig has no bounding-box or mask output feature."""
    return TaskDescriptor(
        id=id,
        label=label,
        modality=modality,
        backend="unsupported",
        status="planned",
        item_spec=ItemSpec(payload="file"),
        annotation=AnnotationSpec(type=ann, requires_label_classes=needs_classes),
        columns=[],
    )


_CLASSIFY = AnnotationSpec(type="classification", requires_label_classes=True)
_FREE_TEXT = AnnotationSpec(type="text_sequence", requires_label_classes=False)
_INLINE = ItemSpec(payload="inline_text")
_RECORD = ItemSpec(payload="record")


def _llm_text_task(id: ProjectTask, label: str, in_cols: list[str], out_col: str) -> TaskDescriptor:
    return _ludwig_task(
        id, label, "text", "experimental", _INLINE, _FREE_TEXT,
        [*(_col(c, "inline_text") for c in in_cols), _col(out_col, "inline_text"), _col(SPLIT, "split")],
        inputs=[_feat(c, "text") for c in in_cols],
        outputs=[_feat(out_col, "text")],
        encoders=[],
        model_type="llm",
    )  # fmt: skip


def _file_caption_task(
    id: ProjectTask, label: str, modality: DatasetModality, path_col: str, out_col: str, in_type: LudwigFeatureType,
    mime: list[str], encoders: list[EncoderChoice],
) -> TaskDescriptor:  # fmt: skip
    return _ludwig_task(
        id, label, modality, "experimental", ItemSpec(payload="file", accept=mime), _FREE_TEXT,
        [_col(path_col, "storage_uri"), _col(out_col, "text_sequence_label"), _col(SPLIT, "split")],
        inputs=[_feat(path_col, in_type)],
        outputs=[_feat(out_col, "text")],
        encoders=encoders,
    )  # fmt: skip


