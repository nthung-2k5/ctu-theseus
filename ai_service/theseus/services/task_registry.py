"""Task registry: the single source of truth for every trainable task.

Ported from server/lib/tasks/{registry,types,index}.ts. It drives project creation, upload
validation, snapshot column derivation, Ludwig config compilation, inference request/response
shapes and export READMEs on the backend, and (via schema/task_registry.json, generated by
scripts/export_schema.py) the task picker and per-modality UI on the frontend.

Adding a trainable task is one entry here, not five edits.

Feature lists are static data. The TypeScript version modelled them as functions of a snapshot
context, but no task ever read that context, and the tabular tasks return an empty list because
their input columns are dataset-defined (the compiler derives those from the snapshot instead).
"""

from dataclasses import dataclass, field
from typing import Any, Literal

from theseus import constants as C
from theseus.db.enums import AnnotationType, DatasetModality, ProjectTask
from theseus.schemas.common import ApiModel

LudwigFeatureType = Literal["image", "text", "audio", "number", "category", "binary", "sequence", "vector"]

# A common, dependency-free subset of Ludwig optimizers (none need bitsandbytes).
LUDWIG_OPTIMIZER_TYPES = ("adam", "adamw", "sgd", "rmsprop", "adagrad")

ColumnKind = Literal[
    "storage_uri", "inline_text", "label", "text_sequence_label", "split", "split_index", "scalar", "item_id"
]
InferenceOutputKind = Literal["classification", "regression", "text", "tokens"]


class ColumnSpec(ApiModel):
    """A column the snapshot builder writes into a version dataset.parquet, in order."""

    name: str
    kind: ColumnKind


class ItemSpec(ApiModel):
    """What one dataset item carries. Drives upload, validation and the pool UI."""

    payload: Literal["file", "inline_text", "record"]
    accept: list[str] | None = None


class AnnotationSpec(ApiModel):
    """Ground truth shape. Drives the Classes page and annotation editors."""

    type: AnnotationType
    requires_label_classes: bool


class EncoderChoice(ApiModel):
    id: str
    label: str
    # Ludwig encoder type value emitted into the compiled config.
    encoder_type: str
    pretrained: bool
    # Extra Ludwig encoder params merged in verbatim (e.g. torchvision model_variant).
    params: dict[str, Any] | None = None


class IntKnob(ApiModel):
    default: int
    min: int
    max: int | None = None


class FloatKnob(ApiModel):
    default: float
    min: float
    max: float | None = None


class BatchSizeKnob(ApiModel):
    default: int | Literal["auto"]
    options: list[int | Literal["auto"]]


class TrainerKnobSpec(ApiModel):
    epochs: IntKnob
    batch_size: BatchSizeKnob
    learning_rate: FloatKnob
    early_stop_patience: IntKnob


class LudwigTaskConfig(ApiModel):
    model_type: Literal["ecd", "llm"]
    input_features: list[dict[str, Any]]
    output_features: list[dict[str, Any]]
    encoders: list[EncoderChoice]
    trainer_knobs: TrainerKnobSpec


class TaskDescriptor(ApiModel):
    id: ProjectTask
    label: str
    modality: DatasetModality
    # The extension seam: a non-Ludwig backend just needs a new value here plus its own runner.
    backend: Literal["ludwig", "unsupported"]
    status: Literal["stable", "experimental", "planned"]
    item_spec: ItemSpec
    annotation: AnnotationSpec
    # Parquet columns the snapshot builder emits, in order.
    columns: list[ColumnSpec]
    # Absent for backend "unsupported" tasks.
    ludwig: LudwigTaskConfig | None = None


@dataclass
class SnapshotContext:
    """Everything the Ludwig compiler needs to know about one dataset version."""

    columns: list[ColumnSpec] = field(default_factory=list)
    # Label class names in a stable order. Empty for non-classification tasks.
    label_class_names: list[str] = field(default_factory=list)
    # Item count per class NAME (classification only), so the compiler can build balanced
    # class_weights without a DB round trip. Keyed by name: Ludwig resolves a name-keyed dict
    # against its own vocabulary, so nothing here needs to know the index Ludwig assigns.
    class_counts: dict[str, int] | None = None


# -- Column and feature shorthands -----------------------------------------------------------

